#Step 1-a
import requests

def get_threat_investigations():
    """
    Fetches investigations from the Qevlar TAM Case API
    and filters them where the verdict is 'Threat'.
    """
    url = "https://qevlar-tam-case-api-production.up.railway.app/investigations"

    # Passing the filter as a query parameter
    params = {
        "verdict": "Threat"
    }

    try:
        response = requests.get(url, params=params)

        # Raise an exception for HTTP errors (4xx, 5xx)
        response.raise_for_status()

        # Parse and return the JSON response
        investigations = response.json()
        return investigations

    except requests.exceptions.HTTPError as http_err:
        print(f"HTTP error occurred: {http_err}")
    except requests.exceptions.ConnectionError as conn_err:
        print(f"Connection error occurred: {conn_err}")
    except requests.exceptions.Timeout as timeout_err:
        print(f"Timeout error occurred: {timeout_err}")
    except requests.exceptions.RequestException as req_err:
        print(f"An error occurred: {req_err}")

    return None

