import requests

def post_high_confidence_feedback(investigations):
    """
    Posts feedback for investigations with confidence_score >= 0.8 to the Qevlar feedback API.
    """
    feedback_url = "https://qevlar-tam-case-api-production.up.railway.app/feedback"
    feedback_count = 0

    if not investigations:
        print("No investigations to process for feedback.")
        return

    print("Checking investigations for high confidence feedback...")
    for investigation in investigations:
        if investigation.get('confidence_score', 0) >= 0.8:
            investigation_id = investigation.get('id', 'N/A')
            feedback_payload = {
                "investigation_id": investigation_id,
                "analyst_verdict": "true_positive",
                "comment": "Auto-confirmed high confidence"
            }
            try:
                print(f"Posting feedback for investigation {investigation_id}...")
                response = requests.post(feedback_url, json=feedback_payload)
                response.raise_for_status()  # Raise an exception for HTTP errors
                print(f"Successfully posted feedback for {investigation_id}. Status Code: {response.status_code}")
                feedback_count += 1
            except requests.exceptions.HTTPError as http_err:
                print(f"HTTP error for investigation {investigation_id}: {http_err}")
            except requests.exceptions.ConnectionError as conn_err:
                print(f"Connection error for investigation {investigation_id}: {conn_err}")
            except requests.exceptions.Timeout as timeout_err:
                print(f"Timeout error for investigation {investigation_id}: {timeout_err}")
            except requests.exceptions.RequestException as req_err:
                print(f"An error occurred while posting feedback for {investigation_id}: {req_err}")

    if feedback_count == 0:
        print("No high confidence investigations found to post feedback for.")
    else:
        print(f"Finished. Posted feedback for {feedback_count} high confidence investigation(s).")

